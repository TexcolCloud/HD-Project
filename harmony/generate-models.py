"""Generate ArkTS interfaces from the shared OpenAPI contract. No third-party packages."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
source = root.parent / 'contracts' / 'openapi.json'
schemas = json.loads(source.read_text(encoding='utf-8'))['components']['schemas']
lines = ['// Generated by harmony/generate-models.py from contracts/openapi.json. Do not hand-edit.',
         '// ArkTS does not support string-literal unions; enum-valued properties use string with contract comments.', '']
extra = {}


def type_of(schema, name):
    if schema.get('allOf'):
        result = type_of(schema['allOf'][0], name)
    elif '$ref' in schema:
        result = schema['$ref'].split('/')[-1]
    elif schema.get('type') == 'array':
        result = type_of(schema['items'], name + 'Item') + '[]'
    elif schema.get('type') == 'object' and schema.get('properties'):
        extra[name] = schema
        result = name
    else:
        result = {'integer': 'number', 'number': 'number', 'boolean': 'boolean',
                  'string': 'string', 'object': 'Object'}.get(schema.get('type'), 'Object')
    return result + (' | null' if schema.get('nullable') else '')


def emit(name, schema):
    if schema.get('type') != 'object':
        values = ', '.join(str(x) for x in schema.get('enum', []))
        lines.append(f'/** Values: {values} */')
        lines.append(f'export type {name} = {type_of(schema, name)};')
        return
    lines.append(f'export interface {name} {{')
    for prop, spec in schema.get('properties', {}).items():
        optional = '' if prop in schema.get('required', []) else '?'
        lines.append(f'  {prop}{optional}: {type_of(spec, name + prop[0].upper() + prop[1:])};')
    lines.append('}')


for name, schema in schemas.items():
    emit(name, schema)
while extra:
    name = next(iter(extra))
    emit(name, extra.pop(name))
(root / 'entry/src/main/ets/models/ApiModels.ets').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Generated ArkTS models from shared OpenAPI:', len(schemas), 'schemas')
