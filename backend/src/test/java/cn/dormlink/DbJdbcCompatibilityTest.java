package cn.dormlink;

import static org.assertj.core.api.Assertions.assertThat;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.Calendar;
import java.util.TimeZone;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

class DbJdbcCompatibilityTest {
  JdbcTemplate jdbc() {
    return new JdbcTemplate(
        new DriverManagerDataSource(
            "jdbc:h2:mem:jdbc-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE",
            "sa",
            ""));
  }

  @Test
  void insertReturnsOnlyTheIdentityWhenOtherColumnsAlsoHaveGeneratedValues() {
    var jdbc = jdbc();
    jdbc.execute(
        "CREATE TABLE sample(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " label VARCHAR(20), calculated BIGINT GENERATED ALWAYS AS (id+1000))");
    var db = new Db(jdbc);
    assertThat(db.insert("INSERT INTO sample(label) VALUES(?)", "fixture")).isEqualTo("1");
    assertThat(db.one("SELECT * FROM sample").get("calculated")).isEqualTo(1001L);
  }

  @Test
  void timestampReadsAndWritesUseUtcIndependentlyOfTheJvmTimeZone() throws Exception {
    TimeZone original = TimeZone.getDefault();
    try {
      TimeZone.setDefault(TimeZone.getTimeZone("Asia/Shanghai"));
      var jdbc = jdbc();
      jdbc.execute("CREATE TABLE sample(id BIGINT PRIMARY KEY, happened_at TIMESTAMP(3))");
      var db = new Db(jdbc);
      var expected = Instant.parse("2026-11-07T05:00:00.123Z");
      db.update("INSERT INTO sample(id,happened_at) VALUES(?,?)", 1L, Timestamp.from(expected));
      try (var c = jdbc.getDataSource().getConnection();
          var s = c.createStatement();
          var row = s.executeQuery("SELECT happened_at FROM sample")) {
        row.next();
        assertThat(
                row.getTimestamp(1, Calendar.getInstance(TimeZone.getTimeZone("UTC"))).toInstant())
            .isEqualTo(expected);
      }
      assertThat(db.one("SELECT happened_at FROM sample").get("happenedAt"))
          .isEqualTo(expected.toString());
      assertThat(
              db.count("SELECT COUNT(*) FROM sample WHERE happened_at=?", Timestamp.from(expected)))
          .isEqualTo(1);
    } finally {
      TimeZone.setDefault(original);
    }
  }
}
